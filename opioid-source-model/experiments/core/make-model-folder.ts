// Writes opioid-source-model/opioid-model/: the authors' model and the files it runs with, copied from
// the SOURCE repository and sorted by what they are for. The model file is copied unchanged, so line
// numbers match the original. findings/ and papers/ are ours and left alone.
// Usage: node opioid-source-model/experiments/core/make-model-folder.ts

import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { FILES, REPO_DIR, loadBundle } from "./inputs.ts";
import { LAYOUT, MODEL_DIR } from "./model-folder.ts";

type Control = { basescens: string[]; scenariolist: string[]; policylist: string[]; testlist: string[] };

main();

function main() {
  const control: Control = JSON.parse(readFileSync(join(REPO_DIR, FILES.controlFile), "utf-8"));
  for (const generated of [LAYOUT.model, LAYOUT.everyRun, LAYOUT.whatIfs, "data", "README.md"]) rmSync(join(MODEL_DIR, generated), { recursive: true, force: true });
  copy(FILES.model, LAYOUT.model);
  for (const file of [FILES.calibrationWeights, FILES.projectionEndValues, FILES.fittedValues]) copy(file, `${LAYOUT.everyRun}/${basename(file)}`);
  const skipped: string[] = [];
  for (const file of readdirSync(join(REPO_DIR, FILES.scenarios)).filter((f) => f.endsWith(".cin"))) {
    const folder = whatIfFolder(file, control);
    if (folder) copy(`${FILES.scenarios}/${file}`, `${LAYOUT.whatIfs}/${folder}/${file}`);
    else skipped.push(file);
  }
  for (const file of FILES.dataFiles) copy(file, `data/${basename(file)}`);
  write(LAYOUT.data, historicalData());
  write("README.md", readme());
  console.log(`Wrote ${MODEL_DIR}${skipped.length ? `; not in any of the authors' run lists, so left out: ${skipped.join(", ")}` : ""}`);
}

// The authors' control file lists which scenario files are futures, policies and tests.
function whatIfFolder(file: string, control: Control): string | null {
  if (file === "NoFentHist.cin") return "history";
  if (control.basescens.includes(file) || control.scenariolist.includes(file)) return "futures";
  if (control.policylist.includes(file)) return "policies";
  if (control.testlist.includes(file)) return "tests";
  return null;
}

function historicalData(): string {
  const bundle = loadBundle();
  const rows = Object.entries(bundle.data).flatMap(([key, series]) => series.times.map((t, i) => `${key}\t${t}\t${series.values[i]}`));
  return [
    `# Historical data the model is compared against, one row per data point, read from the authors' published`,
    `# Base run (${bundle.dataSourceRun}.tab), which keeps data variables at their data points: a readable copy of the .vdf files.`,
    "variable\ttime\tvalue",
    ...rows,
    "",
  ].join("\n");
}

function copy(from: string, to: string) {
  mkdirSync(dirname(join(MODEL_DIR, to)), { recursive: true });
  copyFileSync(join(REPO_DIR, from), join(MODEL_DIR, to));
}

function write(to: string, text: string) {
  mkdirSync(dirname(join(MODEL_DIR, to)), { recursive: true });
  writeFileSync(join(MODEL_DIR, to), text);
}

function readme(): string {
  return `# SOURCE opioid model

The FDA SOURCE model (Lim et al. 2022, Stringfellow et al. 2022), copied from the authors' repository
and sorted by what each file is for. Generated by experiments/core/make-model-folder.ts, except
findings/ and papers/.

- model.mdl: the whole model as authored in Vensim: every equation, fitted values included, and the
  authors' 14 diagrams.
- every-run/: applied to every run: calibration weights, projection end values, and the calibration
  output the fitted values come from.
- what-ifs/: one file per alternative run, each overriding a few constants: futures/, history/
  (no fentanyl), policies/ (at 10, 20 and 50%), tests/.
- data/: the historical data, as the authors' .vdf files and as historical.tsv.
- findings/: claims from the two papers, each with the runs, charts and measures that show it.
- papers/: the two papers.
`;
}
